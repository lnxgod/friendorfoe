fun bundledReferencePhotoUrl(asset: String?): String? = asset
    ?.takeIf { it.isNotBlank() && it !in rejectedReferenceAssets }
    ?.let { "file:///android_asset/$it" }

fun aircraftReferencePhotoUrl(reference: AircraftReference): String? =
    if (reference.id in unavailableAircraftReferences) null else bundledReferencePhotoUrl(reference.photoAsset)

fun droneReferencePhotoUrl(reference: DroneReference): String? =
    if (reference.id == "hoverair_x1_pro") null else bundledReferencePhotoUrl(reference.photoAsset)

fun referenceImageCaption(asset: String): String =
    if (asset == "drones/shahed_136.jpg") "Illustration" else "Reference photo"
